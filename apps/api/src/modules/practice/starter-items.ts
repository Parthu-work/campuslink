import type { CodeLanguage, PracticeDifficulty, PracticeKind, PracticeTopic } from '@campuslink/shared';

/**
 * The starter practice set (prompt 2, G4): original items written for CampusLink, never copied
 * from question dumps or company papers (see docs/specs/practice.md, "The bank"). Copied into a
 * college's bank on first use, where faculty can tag companies, correct or retire them. Placement
 * aptitude tests are set in English, so the items are too; the screens around them are translated.
 * `ref` is permanent: never renumber.
 */
export interface StarterItem {
  ref: string;
  kind: PracticeKind;
  topic: PracticeTopic;
  difficulty: PracticeDifficulty;
  text: string;
  code?: string;
  codeLanguage?: CodeLanguage;
  options?: string[];
  answer: string;
  tolerance?: number;
  explanation: string;
  tests?: { stdin: string; expected: string }[];
}

const mcq = (
  ref: string,
  topic: PracticeTopic,
  difficulty: PracticeDifficulty,
  text: string,
  options: string[],
  answer: number,
  explanation: string,
  extra: Partial<StarterItem> = {},
): StarterItem => ({
  ref,
  kind: 'mcq',
  topic,
  difficulty,
  text,
  options,
  answer: String(answer),
  explanation,
  ...extra,
});
const num = (
  ref: string,
  topic: PracticeTopic,
  difficulty: PracticeDifficulty,
  text: string,
  answer: string,
  explanation: string,
  tolerance?: number,
): StarterItem => ({
  ref,
  kind: 'numeric',
  topic,
  difficulty,
  text,
  answer,
  explanation,
  ...(tolerance ? { tolerance } : {}),
});
const out = (
  ref: string,
  topic: PracticeTopic,
  difficulty: PracticeDifficulty,
  codeLanguage: CodeLanguage,
  code: string,
  answer: string,
  explanation: string,
): StarterItem => ({
  ref,
  kind: 'output_prediction',
  topic,
  difficulty,
  text: 'What does this program print?',
  code,
  codeLanguage,
  answer,
  explanation,
});

