import writeXlsxFile from 'write-excel-file/node';
import {
  APP_NAME,
  currentGradYear,
  gradYearLabel,
  suppress,
  type AccreditationReportId,
  type Branch,
  type CtcBand,
  type ReportCell,
  type ReportColumn,
  type ReportDefinitionView,
  type ReportResultView,
  type ReportsDashboardView,
} from '@campuslink/shared';
import { csvCell } from '../analytics/analytics.service.js';
import { notFound } from '../../lib/errors.js';
import { audit, type RequestMetaLite } from '../audit/audit.service.js';
import type { AuthState } from '../../types.js';
import type { ReportData, ReportDefinition, ReportParams } from './report-data.js';
import { DEFINITIONS, definitionOf } from './definitions/index.js';
import { BAND_LABEL, distinct, groupBy, jobOffers } from './definitions/common.js';
import { pct, placementFigures } from './definitions/internal-placement.js';

const XLSX = 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet';
type Query = { branch?: Branch | undefined; gradYear?: number | undefined };

const viewOf = (d: ReportDefinition): ReportDefinitionView => ({
  id: d.id,
  framework: d.framework,
  title: d.title,
  version: d.version,
  sourceNote: d.sourceNote,
  needsReview: d.needsReview,
  threeYears: d.threeYears,
});

/** A cell as it goes into a download: bands in words, nothing as empty. */
const cellText = (c: ReportColumn, v: ReportCell): string | number =>
  v === null || v === undefined ? '' : c.kind === 'band' ? (BAND_LABEL[v as CtcBand] ?? String(v)) : v;

/**
 * Accreditation and placement reports (B8). Definitions read verified records through
 * `ReportData` and aggregate; counts under 5 are suppressed on screen and in summaries. The
 * evidence workbook (student-level, exact) needs `reports:export` and is audited.
 */
export class ReportsService {
  constructor(
    private readonly data: ReportData,
    private readonly collegeName: () => Promise<string>,
  ) {}

  list(): ReportDefinitionView[] {
    return DEFINITIONS.map(viewOf);
  }

  private load(id: AccreditationReportId) {
    const def = definitionOf(id);
    if (!def) throw notFound('Report');
    return def;
  }

  private params(def: ReportDefinition, q: Query): ReportParams {
    const gradYear = q.gradYear ?? currentGradYear();
    return {
      branch: q.branch ?? null,
      gradYear,
      gradYears: def.threeYears ? [gradYear - 2, gradYear - 1, gradYear] : [gradYear],
    };
  }

  async run(id: AccreditationReportId, q: Query): Promise<ReportResultView> {
    const def = this.load(id);
    const params = this.params(def, q);
    const out = await def.compute(this.data, params, suppress);
    return { ...viewOf(def), params, ...out, generatedAt: new Date().toISOString() };
  }

  private heading(def: ReportDefinition, p: ReportParams, college: string) {
    const years = p.gradYears.map(gradYearLabel).join(', ');
    return [
      [`${college}: ${def.title}`],
      [
        `${def.framework} · version ${def.version}${def.needsReview ? ' · needs review against the current manual' : ''}`,
      ],
      [`Programme: ${p.branch ?? 'All'} · Academic year${p.gradYears.length > 1 ? 's' : ''}: ${years}`],
    ];
  }

  private footer() {
    return `Generated by ${APP_NAME} on ${new Date().toISOString().slice(0, 10)} from verified records.`;
  }

  /** The on-screen table as CSV or Excel (suppressed counts stay suppressed). Audited. */
  async exportSummary(
    actor: AuthState,
    id: AccreditationReportId,
    q: Query,
    format: 'csv' | 'xlsx',
    meta: RequestMetaLite,
  ) {
    const def = this.load(id);
    const p = this.params(def, q);
    const out = await def.compute(this.data, p, suppress);
    const table = this.table(out.columns, out.rows, out.totals);
    const lines = [
      ...this.heading(def, p, await this.collegeName()),
      [],
      ...table,
      [],
      ...out.notes.map((n) => [n]),
      [def.sourceNote],
      [this.footer()],
    ];
    await audit.record(
      {
        action: 'reports.exported',
        actorId: actor.userId,
        targetType: 'report',
        targetId: id,
        meta: { format, branch: p.branch, gradYear: p.gradYear, rows: out.rows.length },
      },
      meta,
    );
    const name = `${id}-${gradYearLabel(p.gradYear)}${p.branch ? `-${p.branch}` : ''}`;
    if (format === 'csv')
      return {
        body: Buffer.from(`\uFEFF${lines.map((r) => r.map(csvCell).join(',')).join('\r\n')}\r\n`),
        type: 'text/csv; charset=utf-8',
        name: `${name}.csv`,
      };
    return { body: await this.xlsx([lines], ['Report']), type: XLSX, name: `${name}.xlsx` };
  }

  /**
   * The evidence workbook: the summary with exact counts and every student behind it, with the
   * footer accreditation teams quote. `reports:export` only, audited with the row count.
   */
  async exportEvidence(actor: AuthState, id: AccreditationReportId, q: Query, meta: RequestMetaLite) {
    const def = this.load(id);
    const p = this.params(def, q);
    const [exact, evidence, college] = await Promise.all([
      def.compute(this.data, p, (n) => n),
      def.evidence(this.data, p),
      this.collegeName(),
    ]);
    const summary = [
      ...this.heading(def, p, college),
      [],
      ...this.table(exact.columns, exact.rows, exact.totals),
      [],
      ...exact.notes.map((n) => [n]),
      [def.sourceNote],
      [this.footer()],
    ];
    const students = [
      ...this.heading(def, p, college),
      [],
      ...this.table(evidence.columns, evidence.rows, null),
      [],
      [this.footer()],
    ];
    await audit.record(
      {
        action: 'reports.evidence_exported',
        actorId: actor.userId,
        targetType: 'report',
        targetId: id,
        meta: { branch: p.branch, gradYear: p.gradYear, rows: evidence.rows.length },
      },
      meta,
    );
    return {
      body: await this.xlsx([summary, students], ['Summary', 'Students']),
      type: XLSX,
      name: `${id}-${gradYearLabel(p.gradYear)}${p.branch ? `-${p.branch}` : ''}-evidence.xlsx`,
    };
  }

  private table(
    columns: ReportColumn[],
    rows: Record<string, ReportCell>[],
    totals: Record<string, ReportCell> | null,
  ): (string | number)[][] {
    return [
      columns.map((c) => c.label),
      ...rows.map((r) => columns.map((c) => cellText(c, r[c.key] ?? null))),
      ...(totals ? [columns.map((c) => cellText(c, totals[c.key] ?? null))] : []),
    ];
  }

  private async xlsx(sheets: (string | number)[][][], names: string[]) {
    const data = sheets.map((rows) =>
      rows.map((r) => r.map((v) => ({ value: v, type: typeof v === 'number' ? Number : String }))),
    );
    return (await writeXlsxFile(
      data as never,
      { buffer: true, sheets: names } as never,
    )) as unknown as Buffer;
  }

  /** The principal's dashboard: this batch's placement %, median band, recruiters and the trend. */
  async dashboard(q: Query): Promise<ReportsDashboardView> {
    const gradYear = q.gradYear ?? currentGradYear();
    const p = { branch: q.branch ?? null };
    const [now, trend, higher] = await Promise.all([
      placementFigures(this.data, gradYear, p),
      Promise.all(
        [4, 3, 2, 1, 0].map(async (back) => {
          const y = gradYear - back;
          const f = await placementFigures(this.data, y, p);
          return { gradYear: y, placementPct: pct(f.all.placed, f.all.seeking) };
        }),
      ),
      this.data.higherStudies([gradYear]),
    ]);
    const recruiters = [...groupBy(jobOffers(now.all.offersRows), (r) => r.companyKey).values()]
      .map((g) => ({ company: g[0]?.companyName ?? '', students: distinct(g, (r) => r.subject) }))
      .sort((a, b) => b.students - a.students || a.company.localeCompare(b.company))
      .slice(0, 5);
    return {
      gradYear,
      finalYear: suppress(now.all.finalYear),
      seeking: suppress(now.all.seeking),
      placed: suppress(now.all.placed),
      placementPct: pct(now.all.placed, now.all.seeking),
      medianBand: now.all.band,
      higherStudies: suppress(
        distinct(
          higher.filter((r) => !p.branch || r.branch === p.branch),
          (r) => r.subject,
        ),
      ),
      topRecruiters: recruiters.map((r) => ({ company: r.company, students: suppress(r.students) })),
      trend,
    };
  }
}
