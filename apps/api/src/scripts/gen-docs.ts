/**
 * Generates docs/permissions.md and docs/api/openapi.json from the live route registry and the
 * shared role map, so the permission matrix can never drift from what the code enforces.
 * Run: pnpm --filter @campuslink/api docs:gen   (CI fails if the committed files are stale)
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  CAPABILITY_PERMISSIONS,
  MFA_REQUIRED_ROLES,
  PERMISSIONS,
  ROLE_PERMISSIONS,
  ROLES,
  UNVERIFIED_PERMISSIONS,
  type Permission,
} from '@campuslink/shared';
import { loadEnv } from '../config/env.js';
import { createLogger } from '../lib/logger.js';
import { MemoryMailProvider } from '../lib/mailer.js';
import { createApp } from '../app.js';
import { buildOpenApi } from '../http/openapi.js';
import type { RouteRegistry } from '../http/registry.js';

export const DOCS_DIR = resolve(dirname(fileURLToPath(import.meta.url)), '../../../../docs');

export function generateDocs(): { permissionsMd: string; openapi: string } {
  const app = createApp({
    env: loadEnv({ NODE_ENV: 'test' }),
    logger: createLogger('silent'),
    readiness: {},
    mailer: new MemoryMailProvider(),
  });
  const registry = app.locals.registry as RouteRegistry;
  const tick = (ok: boolean) => (ok ? '✅' : '·');
  const roleHead = `| Permission | ${ROLES.join(' | ')} |\n|---|${ROLES.map(() => ':-:').join('|')}|`;
  const matrix = (Object.keys(PERMISSIONS) as Permission[])
    .map(
      (p) =>
        `| \`${p}\` ${PERMISSIONS[p]} | ${ROLES.map((r) => tick(ROLE_PERMISSIONS[r].includes(p))).join(' | ')} |`,
    )
    .join('\n');
  const endpoints = registry
    .map(({ spec }) => {
      const who =
        spec.access.kind === 'permission'
          ? `\`${spec.access.permission}\``
          : spec.access.kind === 'authenticated'
            ? 'any signed-in user'
            : 'public';
      const feature = spec.feature ? ` · feature \`${spec.feature}\`` : '';
      return `| \`${spec.method.toUpperCase()} /api/v1${spec.path}\` | ${who}${feature} | ${spec.scope ?? 'college'} | ${spec.limiter ?? '—'} | ${spec.summary} |`;
    })
    .join('\n');
  const permissionsMd = `<!-- GENERATED by apps/api/src/scripts/gen-docs.ts — do not edit by hand. -->
# Permission matrix

Source of truth: \`packages/shared/src/roles.ts\` (enforced by the API, mirrored by the web app for UX only).
Every permission-guarded endpoint is exercised for every role by \`apps/api/test/permissions.test.ts\`.

## Rules
- **Deny by default.** A route without an explicit permission is either public (listed below) or open to any signed-in user of that college for self-service only.
- **Unverified users** (college verification pending) are limited to: ${UNVERIFIED_PERMISSIONS.map((p) => `\`${p}\``).join(', ')}.
- **MFA:** ${MFA_REQUIRED_ROLES.join(', ')} have **no** permissions until TOTP is enabled.
- **Capabilities:** ${Object.entries(CAPABILITY_PERMISSIONS)
    .map(([c, ps]) => `\`${c}\` adds ${ps.map((p) => `\`${p}\``).join(', ')} (students only)`)
    .join('; ')}.
- **Tenant overrides:** a college admin may grant or revoke permissions per role; \`platform:*\` permissions can never be granted to a college role.
- **Escalation guards:** only a college admin can act on another college admin; SUPER_ADMIN cannot be assigned through the college API; the last active college admin cannot be demoted.
- **Feature switches:** an endpoint marked "feature \`x\`" answers 403 \`FEATURE_DISABLED\` while the college has that feature off (Admin › Features), before authentication.
- **Super admin** works only on the platform host and sees aggregate counts — never message content.

## Role defaults
${roleHead}
${matrix}

## Endpoints
| Endpoint | Requires | Host | Rate limit | Purpose |
|---|---|---|---|---|
${endpoints}
`;
  return { permissionsMd, openapi: JSON.stringify(buildOpenApi(registry), null, 2) + '\n' };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) {
  const { permissionsMd, openapi } = generateDocs();
  mkdirSync(resolve(DOCS_DIR, 'api'), { recursive: true });
  writeFileSync(resolve(DOCS_DIR, 'permissions.md'), permissionsMd);
  writeFileSync(resolve(DOCS_DIR, 'api/openapi.json'), openapi);
  console.warn('Wrote docs/permissions.md and docs/api/openapi.json');
}
