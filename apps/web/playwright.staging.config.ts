import { defineConfig, devices } from '@playwright/test';

/**
 * Staging smoke test (deploy/staging/smoke.sh): runs against the production images behind the TLS
 * edge on :8443. No web server is started here; deploy/staging/up.sh starts staging.
 */
const chromium = process.env.PW_CHROMIUM_PATH ? { executablePath: process.env.PW_CHROMIUM_PATH } : {};
// smoke.sh passes the staging certificate's public-key hash, so Chromium trusts exactly that
// certificate (service workers refuse to register over certificate errors, ignored or not).
const spki = process.env.STAGING_CERT_SPKI;
const launchOptions = {
  ...chromium,
  args: [
    '--host-resolver-rules=MAP *.localhost 127.0.0.1',
    ...(spki ? [`--ignore-certificate-errors-spki-list=${spki}`] : []),
  ],
};

export default defineConfig({
  testDir: './e2e-staging',
  workers: 1,
  retries: 0,
  use: {
    baseURL: 'https://dpit.localhost:8443',
    // The staging certificate is self-signed (generated by up.sh).
    ignoreHTTPSErrors: true,
    trace: 'retain-on-failure',
    launchOptions,
  },
  projects: [
    { name: 'desktop', use: { ...devices['Desktop Chrome'], launchOptions, ignoreHTTPSErrors: true } },
  ],
});
